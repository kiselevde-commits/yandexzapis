# ВАЖНО для PythonAnywhere/Amvera: папка /data (или переменная DATA_DIR) постоянная
# и сохраняется между перезапусками. Используем pathlib для кроссплатформенности.
# ---------------------------------------------------------------------------
def _get_default_db_path() -> str:
    # На PythonAnywhere постоянная директория обычно /home/username/
    # На Amvera — /data
    # Локально — текущая папка проекта
    data_dir = os.environ.get("DATA_DIR")
    if data_dir:
        return str(Path(data_dir) / "schedule.db")
    if os.path.exists("/data") and os.path.isdir("/data"):
        return "/data/schedule.db"
    # Fallback: папка проекта
    return str(Path(__file__).parent / "schedule.db")

