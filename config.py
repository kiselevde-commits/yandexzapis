def get_all_admin_ids() -> list[int]:
    """
    Возвращает список всех Telegram ID администраторов.

    Объединяет два источника:
      1) статический список ADMIN_IDS из этого файла;
      2) динамический список ID, сохранённый ботом в JSON-файле ADMIN_IDS_FILE.

    Используется, чтобы показать кнопку меню /admin каждому администратору
    (в том числе добавленному уже после запуска бота).
    """
    # Начинаем со статических админов, убираем возможные дубликаты через set.
    admin_ids: set[int] = set(ADMIN_IDS)

    # Читаем динамический список из JSON-файла, если он существует.
    if os.path.exists(ADMIN_IDS_FILE):
        try:
            with open(ADMIN_IDS_FILE, "r", encoding="utf-8") as f:
                data = json.load(f)
            # Ожидаем список чисел; на всякий случай фильтруем по типу int.
            if isinstance(data, list):
                for item in data:
                    if isinstance(item, int):
                        admin_ids.add(item)
        except (json.JSONDecodeError, OSError):
            # Если файл повреждён или недоступен — просто игнорируем его,
            # остаются статические админы из ADMIN_IDS.
            pass

    return list(admin_ids)